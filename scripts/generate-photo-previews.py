"""Build small, unblurred previews + dominant colours; CSS applies the 20px blur.
Run with Python 3 + Pillow. Generated files are checked in; hosting needs no build.
"""
from pathlib import Path
import json
import re
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
(ROOT / 'assets/images/previews').mkdir(parents=True, exist_ok=True)
config = (ROOT / 'assets/js/orbit-config.js').read_text()
sources = sorted(set(re.findall(r"'((?:assets/images/)[^']+)'", config)))
metadata = {}
for source in sources:
    with Image.open(ROOT / source) as original:
        image = ImageOps.exif_transpose(original).convert('RGB')
        width, height = image.size
        image.thumbnail((40, 40), Image.Resampling.LANCZOS)
        palette = image.quantize(colors=8)
        _, colour_index = max(palette.getcolors(), key=lambda pair: pair[0])
        rgb = palette.getpalette()[colour_index * 3:colour_index * 3 + 3]
        colour = '#' + ''.join(f'{v:02x}' for v in rgb)
        preview = 'assets/images/previews/' + Path(source).stem + '.jpg'
        image.save(ROOT / preview, 'JPEG', quality=55, optimize=True)
        metadata[source] = dict(preview=preview, colour=colour, width=width, height=height)
(ROOT / 'assets/js/photo-previews.js').write_text(
    '// Generated by scripts/generate-photo-previews.py.\nwindow.PHOTO_PREVIEWS = ' +
    json.dumps(metadata, ensure_ascii=False, indent=2) + ';\n')
print(f'Generated {len(metadata)} previews')
